// Преобразование категории в материал для SEO
function mapMaterialForSeo(?string $category): string
{
    $category = trim((string)$category);

    switch (mb_strtoupper($category, 'UTF-8')) {
        case 'ПВХ':
            return 'ПВХ-профиля';
        case 'АЛЮМИНИЙ':
        case 'АЛЮМИНИЕВЫЕ':
            return 'алюминиевого профиля';
        case 'СТЕКЛО':
            return 'стекла и стеклопакетов';
        case 'МОНТАЖ':
            return 'окон и дверей';
        default:
            return mb_strtolower($category, 'UTF-8') ?: 'оконных профилей';
    }
}




// Выбор SEO-шаблона по типу станка
function getSeoTemplatesForType(?string $type, array $seoTypeTemplates, array $seoDefaultTemplates): array
{
    $key = mb_strtoupper(trim((string)$type), 'UTF-8');

    if (isset($seoTypeTemplates[$key])) {
        return $seoTypeTemplates[$key];
    }

    return $seoDefaultTemplates;
}

// Рендеринг шаблона с подстановкой переменных
function renderSeoTemplate(string $template, array $machine): string
{
    $material = $machine['material'] ?? mapMaterialForSeo($machine['category'] ?? '');

    $replacements = [
        '{{CODE}}'     => $machine['code']     ?? '',
        '{{TITLE}}'    => $machine['title']    ?? '',
        '{{TYPE}}'     => $machine['type']     ?? '',
        '{{CATEGORY}}' => $machine['category'] ?? '',
        '{{MATERIAL}}' => $material,
    ];

    return str_replace(array_keys($replacements), array_values($replacements), $template);
}

// Проходим по всем станкам и дописываем им SEO-поля
foreach ($machines as &$machine) {
    if (!isset($machine['material'])) {
        $machine['material'] = mapMaterialForSeo($machine['category'] ?? '');
    }

    $templates = getSeoTemplatesForType($machine['type'] ?? '', $seoTypeTemplates, $seoDefaultTemplates);

    $machine['seo_title']       = renderSeoTemplate($templates['title'], $machine);
    $machine['seo_description'] = renderSeoTemplate($templates['description'], $machine);
    $machine['seo_text']        = renderSeoTemplate($templates['text'], $machine);
}
unset($machine);